# falcon-pa setup (Windows) — run once from your clone: powershell -ExecutionPolicy Bypass -File bin\setup.ps1
# Installs the two launcher commands (claude-pa.cmd, codex-pa.cmd) pointed at THIS
# clone, and the Claude Code output style + settings that make claude-pa speak plainly.
$ErrorActionPreference = 'Stop'

if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Write-Error "Node.js not found. Install Node >= 22.5 first: https://nodejs.org"
}
$nodeOk = node -e 'const [a,b]=process.versions.node.split(".").map(Number); console.log(a>22||(a===22&&b>=5)?"y":"n")'
if ($nodeOk -ne 'y') {
  Write-Error "Node $(node -v) is too old. The brain needs Node >= 22.5."
}
if (-not (Get-Command claude -ErrorAction SilentlyContinue) -and -not (Get-Command codex -ErrorAction SilentlyContinue)) {
  Write-Warning "neither 'claude' nor 'codex' found on PATH - install Claude Code or Codex before starting."
}

$PaHome = Split-Path -Parent $PSScriptRoot
$BinDir = Join-Path $env:USERPROFILE '.local\bin'
New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $env:USERPROFILE '.claude\output-styles') | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $env:USERPROFILE '.claude\pa') | Out-Null

Copy-Item (Join-Path $PaHome 'config\pa-speak.md') (Join-Path $env:USERPROFILE '.claude\output-styles\pa-speak.md') -Force
Copy-Item (Join-Path $PaHome 'config\pa-settings.json') (Join-Path $env:USERPROFILE '.claude\pa\settings.json') -Force

@"
@echo off
rem claude-pa — your business PA on Claude Code (generated by falcon-pa bin\setup.ps1).
cd /d "$PaHome"
claude --dangerously-skip-permissions --settings "%USERPROFILE%\.claude\pa\settings.json" %*
"@ | Set-Content -Encoding ASCII (Join-Path $BinDir 'claude-pa.cmd')

@"
@echo off
rem codex-pa — your business PA on Codex (generated by falcon-pa bin\setup.ps1).
rem The plain-speech rules and brain teaching load from AGENTS.md in the PA folder.
cd /d "$PaHome"
codex --sandbox danger-full-access %*
"@ | Set-Content -Encoding ASCII (Join-Path $BinDir 'codex-pa.cmd')

Write-Host "falcon-pa setup complete."
Write-Host "  PA folder : $PaHome"
Write-Host "  Commands  : claude-pa, codex-pa (in $BinDir)"
Write-Host "If $BinDir is not on your PATH, add it:"
Write-Host "  [Environment]::SetEnvironmentVariable('Path', `$env:Path + ';$BinDir', 'User')"
Write-Host "Next: open a NEW terminal and type claude-pa (or codex-pa). On first run the"
Write-Host "PA installs its brain and asks your name and timezone."
